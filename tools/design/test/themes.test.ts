import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
// @ts-expect-error plain .mjs data files with no types
import { THEMES } from '../themes.mjs';
// @ts-expect-error plain .mjs generator with no types
import { files, stale } from '../build-themes.mjs';

const here = dirname(fileURLToPath(import.meta.url));

describe('the palette data', () => {
  it('is the source of the generated stylesheets: nothing on disk differs (run node tools/design/build-themes.mjs)', () => {
    expect(stale()).toEqual([]);
    expect(files().map((f: { path: string }) => f.path.split('/').pop())).toEqual(['graphite.css', 'linen.css', 'harbor.css']);
  });

  it('gives all three themes the same names in light and in dark', () => {
    const names = (t: { light: object; dark: object }) => [Object.keys(t.light).sort(), Object.keys(t.dark).sort()];
    const [lightRef, darkRef] = names(THEMES[0]);
    for (const t of THEMES) {
      const [light, dark] = names(t);
      expect(light).toEqual(lightRef);
      expect(dark).toEqual(darkRef);
      expect(lightRef).toEqual(darkRef);
      expect(Object.keys(t.look).sort()).toEqual(Object.keys(THEMES[0].look).sort());
    }
  });

  it('names every new token of the design (accent, controls, focus, code, run card, to-do card, elevation, type, spacing, motion)', () => {
    const need = ['accent', 'accent-hover', 'on-accent', 'control-border', 'control-bg', 'focus-ring', 'code-bg', 'code-border', 'code-ink', 'selection', 'run-bg', 'run-border', 'run-rail', 'run-state-ink', 'run-pulse', 'todo-bg', 'todo-border', 'todo-track', 'todo-fill', 'elev-1', 'elev-2', 'elev-3'];
    const look = ['font-display', 'fw-display', 'ls-title', 'ls-body', 'ls-caps', 'radius-xs', 'ctl-h', 'ctl-pad-x', 'sp-1', 'sp-6', 'row-h', 'dur-fast', 'dur-pulse', 'run-rail-w', 'border-w'];
    for (const t of THEMES) {
      for (const k of need) expect(Object.keys(t.light), `${t.id} light ${k}`).toContain(k);
      for (const k of need) expect(Object.keys(t.dark), `${t.id} dark ${k}`).toContain(k);
      for (const k of look) expect(Object.keys(t.look), `${t.id} ${k}`).toContain(k);
    }
  });

  it('writes no raw colour outside tokens.css and the generated files', () => {
    const generated = readFileSync(join(here, '..', '..', '..', 'clients', 'web', 'src', 'styles', 'themes', 'linen.css'), 'utf8');
    expect(generated).toMatch(/GENERATED by tools\/design\/build-themes\.mjs/);
  });
});
