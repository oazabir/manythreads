// P28-01: writes clients/web/src/styles/themes/<id>.css from tools/design/themes.mjs.
//   node tools/design/build-themes.mjs          write the files
//   node tools/design/build-themes.mjs --check  exit 1 when a file on disk differs (the unit test and `pnpm lint` use the same function)
//
// Selectors (design: docs/design/themes.md, "How a theme is applied"):
//   :root[data-palette="P"]                        the look of the palette (type, corners, spacing, motion)
//   :root[data-palette="P"][data-theme="light|dark"]  its colours; data-theme keeps meaning light or dark
// The same blocks also match a nested element with the same attributes (`[data-palette="P"]:not(:root)`), which is how a swatch on the Appearance
// page and a column of /dev/tokens draw another palette next to the page's own. A custom property that reads another one keeps the value it had
// where it was declared, so the shared block in tokens.css that builds aliases lists `[data-palette]` as well.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEMES } from './themes.mjs';

const here = dirname(fileURLToPath(import.meta.url));
export const OUT_DIR = join(here, '..', '..', 'clients', 'web', 'src', 'styles', 'themes');

const block = (selectors, decls) =>
  `${selectors.join(',\n')} {\n${decls.map(([k, v]) => `  ${k.startsWith('--') || k === 'color-scheme' ? k : `--${k}`}: ${v};`).join('\n')}\n}\n`;

/** One palette's stylesheet as text. */
export function cssFor(theme) {
  const id = theme.id;
  const page = (extra = '') => [`:root[data-palette="${id}"]${extra}`, `[data-palette="${id}"]${extra}:not(:root)`];
  const head = `/* stylelint-disable color-hex-length, custom-property-empty-line-before, value-keyword-case -- generated file */

/*
 * ${theme.name}: ${theme.mood}
 * GENERATED by tools/design/build-themes.mjs from tools/design/themes.mjs: edit the data there, never this file (a test fails when they differ).
 * The one place besides tokens.css where raw colours are allowed (stylelint override). Design: docs/design/themes.md.
 */
`;
  const colour = (mode) => {
    const entries = Object.entries(theme[mode]);
    return [['color-scheme', mode], ...entries];
  };
  return (
    head +
    '\n' +
    block(page(), Object.entries(theme.look)) +
    '\n' +
    block(page('[data-theme="light"]'), colour('light')) +
    '\n' +
    block(page('[data-theme="dark"]'), colour('dark'))
  );
}

export function files() {
  return THEMES.map((t) => ({ path: join(OUT_DIR, `${t.id}.css`), text: cssFor(t) }));
}

/** The files whose text on disk differs from what the data produces. */
export function stale() {
  return files().filter((f) => !existsSync(f.path) || readFileSync(f.path, 'utf8') !== f.text).map((f) => f.path);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const bad = stale();
    for (const p of bad) console.log(`out of date: ${p} (run node tools/design/build-themes.mjs)`);
    process.exit(bad.length ? 1 : 0);
  }
  mkdirSync(OUT_DIR, { recursive: true });
  for (const f of files()) writeFileSync(f.path, f.text);
  console.log(`wrote ${files().length} palette stylesheets to ${OUT_DIR}`);
}
