// The words of seed v3: what the people of Kahf Software say in their channels. Plain data, no side effects (seed-content.ts writes it).
// Authors are persona keys; `@name` in a text is a mention (seed-content.ts records the row); a line may carry reactions.

export type SeedAuthor = 'omar' | 'nadia' | 'rafi' | 'sameera' | 'tariq' | 'priya';
export type SeedEmoji = '👍' | '🎉' | '👀' | '✅' | '🔥' | '🙏' | '😄';

export interface SeedLine {
  who: SeedAuthor;
  text: string;
  /** Who reacted with what. */
  react?: [SeedEmoji, ...SeedAuthor[]][];
  /** The mention (if any) raises an unread notification for the person it names. */
  notify?: boolean;
  /** The text was edited a little after it was posted. */
  edited?: true;
  /** Marks the root of the "Deploy plan" thread (#dev), which also carries the attachment. */
  key?: 'deploy-plan';
}

const l = (who: SeedAuthor, text: string, extra: Omit<SeedLine, 'who' | 'text'> = {}): SeedLine => ({ who, text, ...extra });

