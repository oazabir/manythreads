/** 10 working days of standup posts, four people a day. */
export function standupLines(): SeedLine[] {
  const out: SeedLine[] = [];
  for (let day = 0; day < 10; day += 1) {
    for (const who of ['rafi', 'nadia', 'priya', 'omar'] as const) {
      const y = STANDUP_YESTERDAY[who]![day]!;
      const t = STANDUP_TODAY[who]![day]!;
      const blockers = day === 6 && who === 'priya' ? 'waiting on a laptop charger, otherwise none' : 'none';
      out.push(l(who, `**Yesterday:** ${y}. **Today:** ${t}. **Blockers:** ${blockers}.`));
    }
  }
  return out;
}

