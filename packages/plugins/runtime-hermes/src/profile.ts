import type { BotRuntimeInput, BotRuntimeProfile } from '@manythreads/sdk';

// The profile a Hermes run executes in (SPEC §7.1, §10.2; PLAN P5-10: "render profile from BOT.md (body is SOUL.md)").
//
// A Hermes profile is a home directory (`HERMES_HOME`) holding `config.yaml` and `SOUL.md`; `hermes -p` / `HERMES_HOME=` pick
// which one a process uses, so one run gets one directory and nothing of the bot is shared by accident. What the platform
// renders, and nothing more:
//
//  * `SOUL.md` is the BOT.md body, verbatim — the agent's identity and behaviour, written by the team in the repo.
//  * `config.yaml` points the profile at two endpoints, never at a provider key: the workspace's LiteLLM gateway with the
//    bot's own virtual key (aliases, budgets, rate limits and the DLP hook live there, SPEC §10.1–10.2), and the run's MCP
//    endpoint (`ctx.runs.open`) with the run token — the per-run URL of `docs/spikes/per-run-scoping.md`, which is what
//    makes every tool call attributable to this run alone.
//
// No provider credential, no Hindsight address, no repo credential is ever written here: the run token is the bot's whole
// authority, and it dies with the run. The file is generated on every run (the token and the URL change every time), so it
// carries a header saying so.
//
// The YAML is written by hand rather than serialised from an object: the file is short, every value is a scalar we control,
// and a hand-written file can carry the provenance comment and stay byte-stable for a test. Strings are quoted the way JSON
// quotes them, which is valid YAML for every one of them.

/** One YAML scalar we control (a slug, a URL, a key or a token): a double-quoted JSON string is always a valid YAML scalar. */
const scalar = (value: string): string => JSON.stringify(value);

/** The default MCP call timeout of a rendered profile, in seconds (the gateway answers a tool call in well under a second). */
const MCP_TIMEOUT_SECONDS = 120;
const MCP_CONNECT_TIMEOUT_SECONDS = 30;

/** The profile's directory name: the bot's slug and the run id, both already restricted to path-safe characters. */
export function profileHome(input: BotRuntimeInput): string {
  const run = input.endpoint?.runId ?? 'no-run';
  return `${input.bot.slug}-${run}`;
}

/**
 * The Hermes `config.yaml` for one run. `alias` is the first of the definition's `model.aliases` (the gateway's ordered
 * fallbacks take over from there); `effort` becomes `agent.reasoning_effort`. Both are absent for a rules-only definition,
 * which `runtime-hermes` never renders — a bot whose runtime is `rules` has no profile here at all.
 */
export function renderConfig(input: BotRuntimeInput): string {
  const alias = input.definition.frontmatter.model?.aliases?.[0];
  const effort = input.definition.frontmatter.model?.effort;
  const gateway = input.gateway;
  const endpoint = input.endpoint;
  if (!alias) throw new Error(`bot ${input.bot.slug}: a hermes run needs model.aliases[0] in its BOT.md`);
  if (!gateway) throw new Error(`bot ${input.bot.slug}: no LLM gateway is configured for this workspace`);
  if (!endpoint) throw new Error(`bot ${input.bot.slug}: a hermes run needs the run's own MCP endpoint`);

  const lines = [
    `# Generated by manythreads for bot ${input.bot.slug} (run ${endpoint.runId}, trigger ${input.trigger}).`,
    '# Do not edit: the next run of this bot writes this file again. The body of BOT.md is SOUL.md beside it.',
    'model:',
    '  provider: "manythreads"',
    `  default: ${scalar(alias)}`,
  ];
  if (effort) lines.push('agent:', `  reasoning_effort: ${scalar(effort)}`);
  lines.push(
    'providers:',
    '  manythreads:',
    '    name: "manythreads"',
    `    api: ${scalar(`${gateway.baseUrl.replace(/\/+$/, '')}/v1`)}`,
    ...(gateway.key ? [`    api_key: ${scalar(gateway.key)}`] : []),
    '    transport: "chat_completions"',
    `    default_model: ${scalar(alias)}`,
    'mcp_servers:',
    '  manythreads:',
    `    url: ${scalar(endpoint.url)}`,
    '    headers:',
    `      Authorization: ${scalar(`Bearer ${endpoint.token}`)}`,
    `    timeout: ${MCP_TIMEOUT_SECONDS}`,
    `    connect_timeout: ${MCP_CONNECT_TIMEOUT_SECONDS}`,
  );
  return `${lines.join('\n')}\n`;
}

/** The whole profile: the two files and the home they sit in. Pure — the same run input renders the same bytes. */
export function renderProfile(input: BotRuntimeInput): BotRuntimeProfile {
  return {
    home: profileHome(input),
    files: {
      'SOUL.md': `${input.definition.body.trimEnd()}\n`,
      'config.yaml': renderConfig(input),
    },
  };
}

/** The argv after the binary (and any prefix): one one-shot turn, structured JSONL on stdout, the query on stdin. */
export function chatArgs(input: BotRuntimeInput): string[] {
  const args = ['chat', '--query-file', '-', '--oneshot', '--format', 'stream-json'];
  if (input.limits.runBudgetSeconds !== null) args.push('--run-budget', String(input.limits.runBudgetSeconds));
  if (input.limits.maxTurns !== null) args.push('--max-turns', String(input.limits.maxTurns));
  return args;
}
