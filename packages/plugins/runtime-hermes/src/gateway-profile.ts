import type { BotRuntimeDefinition } from '@manythreads/sdk';
import { hermesToolsets } from './toolsets.ts';

// The profile of a managed bot (mode B): the three files that make a bot a profile in the team's Hermes pod. Pure — the same input gives the same
// bytes, so a test can pin them and a controller can tell a changed profile from an unchanged one by comparing files.
//
//  * `SOUL.md` is the BOT.md body, verbatim: who the bot is.
//  * `config.yaml` names the model (the in-cluster LLM gateway, with the bot's own virtual key), the tools the definition grants
//    (`toolsets.ts`), the terminal the bot's commands run in, and manythreads' MCP server at the bot's stable address. It refers to every secret
//    by variable name (`${NAME}`), never by value: Hermes fills those from the profile's `.env`.
//  * `.env.template` lists the variables the profile's `.env` must define, with no values. The controller writes the real `.env` from the secrets
//    the `hermes.profiles` provider hands it.
//
// `tools.tool_search.enabled: "off"` is required: with the default, Hermes hides MCP tools behind a search tool and the model never sees the
// manythreads tools directly.

/** The names the profile's `.env` defines. `API_SERVER_KEY` is Hermes' own name for the key that authorises requests to the profile. */
export const GATEWAY_ENV = { mcpToken: 'MANYTHREADS_MCP_TOKEN', llmKey: 'MANYTHREADS_LLM_KEY', apiServerKey: 'API_SERVER_KEY' } as const;

export interface GatewayProfileInput {
  botSlug: string;
  /** The bot's stable MCP address, `http://manythreads-server:3000/mcp` inside the cluster (the same path for every bot; the bot's token says which). Carries no credential. */
  mcpUrl: string;
  /** The `.env` variable holding the bot's token for that address. */
  mcpTokenVar: string;
  model: {
    /** The LLM gateway's address, `http://manythreads-litellm:4000/v1` inside the cluster. */
    baseUrl: string;
    /** The `.env` variable holding the bot's virtual key at that gateway. */
    apiKeyVar: string;
    /** The gateway alias the definition names first (`smart`, `fast`, ...). */
    alias: string;
  };
  /** Where the bot's commands run. Only `ssh` is rendered: a bot's shell is never the pod's own. Omitted when the bot may not run commands. */
  terminal?: { backend: 'ssh'; host: string; user: string; cwd: string };
}

export interface GatewayProfileFiles {
  'SOUL.md': string;
  'config.yaml': string;
  '.env.template': string;
}

const scalar = (value: string): string => JSON.stringify(value);
const ENV_NAME = /^[A-Z][A-Z0-9_]{1,63}$/;
const MCP_TIMEOUT_SECONDS = 120;
const MCP_CONNECT_TIMEOUT_SECONDS = 30;

export function renderGatewayProfile(definition: BotRuntimeDefinition, input: GatewayProfileInput): GatewayProfileFiles {
  for (const name of [input.mcpTokenVar, input.model.apiKeyVar]) {
    if (!ENV_NAME.test(name)) throw new Error(`"${name}" is not a usable environment variable name`);
  }
  const effort = definition.frontmatter.model?.effort;
  const toolsets = hermesToolsets(definition.frontmatter.capabilities?.runtime);
  const lines = [
    `# Generated by manythreads for bot ${input.botSlug}. Do not edit: the next change to the bot writes this file again.`,
    '# The body of BOT.md is SOUL.md beside it. Secrets are named here and defined in .env.',
    'model:',
    '  provider: "manythreads"',
    `  default: ${scalar(input.model.alias)}`,
    'providers:',
    '  manythreads:',
    '    name: "manythreads"',
    `    api: ${scalar(input.model.baseUrl.replace(/\/+$/, ''))}`,
    `    api_key: ${scalar(`\${${input.model.apiKeyVar}}`)}`,
    '    transport: "chat_completions"',
    `    default_model: ${scalar(input.model.alias)}`,
    'platform_toolsets:',
    `  api_server: [${toolsets.enabled.map(scalar).join(', ')}]`,
    'agent:',
    ...(effort ? [`  reasoning_effort: ${scalar(effort)}`] : []),
    `  disabled_toolsets: [${toolsets.disabled.map(scalar).join(', ')}]`,
    // Without this Hermes shows MCP tools only through a search tool, and the model never calls the manythreads tools directly.
    'tools:',
    '  tool_search:',
    '    enabled: "off"',
  ];
  if (input.terminal) {
    lines.push(
      'terminal:',
      `  backend: ${scalar(input.terminal.backend)}`,
      `  ssh_host: ${scalar(input.terminal.host)}`,
      `  ssh_user: ${scalar(input.terminal.user)}`,
      `  cwd: ${scalar(input.terminal.cwd)}`,
    );
  }
  lines.push(
    'mcp_servers:',
    '  manythreads:',
    `    url: ${scalar(input.mcpUrl)}`,
    '    headers:',
    `      Authorization: ${scalar(`Bearer \${${input.mcpTokenVar}}`)}`,
    `    timeout: ${MCP_TIMEOUT_SECONDS}`,
    `    connect_timeout: ${MCP_CONNECT_TIMEOUT_SECONDS}`,
  );
  return {
    'SOUL.md': `${definition.body.trimEnd()}\n`,
    'config.yaml': `${lines.join('\n')}\n`,
    '.env.template': [
      `# The secrets of profile mt-${input.botSlug}. Written by the controller from the hermes.profiles provider; never commit a filled copy.`,
      `${GATEWAY_ENV.apiServerKey}=`,
      `${input.mcpTokenVar}=`,
      `${input.model.apiKeyVar}=`,
      '',
    ].join('\n'),
  };
}
