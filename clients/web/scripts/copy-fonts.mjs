// P28-03: copies the self-hosted palette fonts out of the @fontsource packages into public/fonts and writes src/styles/fonts-palettes.css.
//   node scripts/copy-fonts.mjs
// The output is committed (like the Inter files beside it), so a build needs no network and the packages are only needed to run this script again.
// Subsets kept: latin, latin-ext, cyrillic (the scripts Inter's own files cover besides Greek and Vietnamese; those fall back to the system face).
// Arabic stays the system fallback (design: docs/design/themes.md). A face nobody uses is never downloaded: every @font-face has a unicode-range.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..');
const require = createRequire(join(web, 'package.json'));
const OUT = join(web, 'public', 'fonts');
const KEEP = new Set(['latin', 'latin-ext', 'cyrillic']);

// [package, css file in the package, family name the palettes use, family name the package writes]
const SOURCES = [
  ['@fontsource/ibm-plex-sans', '400.css', 'IBM Plex Sans'],
  ['@fontsource/ibm-plex-sans', '500.css', 'IBM Plex Sans'],
  ['@fontsource/ibm-plex-sans', '600.css', 'IBM Plex Sans'],
  ['@fontsource/ibm-plex-mono', '400.css', 'IBM Plex Mono'],
  ['@fontsource-variable/source-serif-4', 'wght.css', 'Source Serif 4'],
  ['@fontsource-variable/geist', 'wght.css', 'Geist'],
  ['@fontsource-variable/geist-mono', 'wght.css', 'Geist Mono'],
];

mkdirSync(OUT, { recursive: true });
const parts = [
  `/*
 * GENERATED by clients/web/scripts/copy-fonts.mjs from the @fontsource packages (SIL OFL, see docs/third-party-assets.md): the faces of Linen (IBM Plex Sans and
 * Mono, Source Serif 4) and Harbor (Geist, Geist Mono). Graphite keeps Inter (fonts.css). Served from public/fonts, never from a CDN; latin, latin-ext and
 * cyrillic only; a face the page does not draw is not downloaded (unicode-range), and theme-boot.js preloads only the chosen palette's text face.
 */
`,
];
const seen = new Set();
for (const [pkg, cssFile, family] of SOURCES) {
  const dir = dirname(require.resolve(`${pkg}/package.json`));
  const css = readFileSync(join(dir, cssFile), 'utf8');
  for (const m of css.matchAll(/\/\*\s*([^*]+?)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)) {
    const label = m[1];
    const subset = /-(latin-ext|latin|cyrillic-ext|cyrillic|greek-ext|greek|vietnamese|math|symbols\d?)-/.exec(label)?.[1];
    if (!subset || !KEEP.has(subset)) continue;
    const woff2 = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(m[2])?.[1];
    if (!woff2) continue;
    if (!seen.has(woff2)) {
      copyFileSync(join(dir, 'files', woff2), join(OUT, woff2));
      seen.add(woff2);
    }
    const face = m[2]
      .replace(/font-family:\s*'[^']+'/, `font-family: ${family.includes(" ") ? `"${family}"` : family}`)
      .replace(/src:[^;]+;/, `src: url("/fonts/${woff2}") format("woff2");`)
      .replace(/unicode-range:\s*([^;]+);/, (_, r) => `unicode-range: ${r.split(',').join(', ')};`)
      .replace(/\n\s*\n/g, '\n');
    parts.push(`/* ${label} */\n${face}\n`);
  }
}
writeFileSync(join(web, 'src', 'styles', 'fonts-palettes.css'), parts.join('\n'));
console.log(`copied ${seen.size} font files to ${OUT}`);
